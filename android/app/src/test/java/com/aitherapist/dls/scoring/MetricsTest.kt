package com.aitherapist.dls.scoring

import java.io.File
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.jsonObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Test

/** Parity with `tools/eval/compute_metrics.py` on the shared fixtures (Story 5.8 part B). */
class MetricsTest {
    private val dir = File(checkNotNull(System.getProperty("evalFixturesDir")) { "evalFixturesDir not set by Gradle" })

    private fun clips(): Map<String, String> = Metrics.parse(File(dir, "metrics_clips.csv").readText()).associate {
        it["file"] to
            it["outcome"]
    }

    private fun Metrics.Result.asMap(): Map<String, Any?> = mapOf(
        "attempts" to attempts,
        "app_cannot_tell" to appCannotTell,
        "cannot_tell_rate" to cannotTellRate,
        "rated" to rated,
        "unrated" to unrated,
        "either_cannot_tell" to eitherCannotTell,
        "decided" to decided,
        "agree" to agree,
        "agreement" to agreement,
        "steps" to steps,
        "kappa_pairs" to kappaPairs.size,
        "kappa" to kappa,
        "partial_steps" to partialSteps,
        "not_scored_steps" to notScoredSteps,
        "app_open_steps" to appOpenSteps,
        "blind_open_steps" to blindOpenSteps,
        "corrected_steps" to correctedSteps,
        "corrected_changed" to correctedChanged,
        "clip_matched" to clipMatched,
        "clip_decided" to clipDecided,
        "clip_agree" to clipAgree,
        "clip_cannot_tell" to clipCannotTell,
        "clip_agreement" to clipAgreement,
        "unmatched" to unmatched
    )

    private fun assertSame(expected: Map<String, Any?>, actual: Map<String, Any?>) {
        assertEquals(expected.keys, actual.keys)
        expected.forEach { (key, value) ->
            val got = actual[key]
            when (value) {
                null -> assertNull(key, got)
                is Double -> assertEquals(key, value, got as Double, 1e-12)
                else -> assertEquals(key, value, got)
            }
        }
    }

    private fun expectedJson(name: String): Map<String, Any?> {
        val json = Json.parseToJsonElement(File(dir, name).readText()).jsonObject
        return json.mapValues { (_, v) ->
            when {
                v is JsonNull -> null
                v is JsonArray -> v.map { (it as JsonPrimitive).content }
                (v as JsonPrimitive).content.contains('.') -> v.content.toDouble()
                else -> v.content.toInt()
            }
        }
    }

    @Test
    fun fixtureMatchesExpectedJson() {
        val expected = expectedJson("metrics_fixture.expected.json")
        val result = Metrics.compute(Metrics.parse(File(dir, "metrics_fixture.csv").readText()), clips())
        assertSame(expected, result.asMap())
        assertEquals(7.0 / 12, result.kappa!!, 1e-12)
        assertEquals(true, result.agreementMet)
        assertEquals(false, result.kappaMet)
        assertEquals(false, result.cannotTellMet)
        assertEquals(mapOf((Metrics.CANNOT_TELL to Metrics.DONE) to 1), result.confusion["fixture.g"])
    }

    /** `results_export_sample.expected.json` is generated by `compute_metrics.py` and checked by pytest too. */
    @Test
    fun exportSampleMatchesPython() {
        val result = Metrics.compute(Metrics.parse(File(dir, "results_export_sample.csv").readText()))
        assertSame(expectedJson("results_export_sample.expected.json"), result.asMap())
        assertNull(result.kappaMet)
    }

    private val badHead = "sessionId,stepId,attemptId,attemptNumber,promptLevel,verdict,level,correctedLevel,blindVerdict,clipFile\n"

    private fun bad(vararg lines: String) {
        assertThrows(IllegalArgumentException::class.java) { Metrics.compute(Metrics.parse(badHead + lines.joinToString("\n") + "\n")) }
    }

    @Test
    fun badInputIsRejectedLikePython() {
        bad("s,a,a1,1,1,maybe,3,,,")
        bad("s,a,a1,1,1,done,3,,yes,")
        bad("s,a,a1,2,1,not_done,,,,", "s,a,a2,1,1,done,3,,,")
        bad("s,a,,,,,3,2,,")
        bad("s,a,,,,,,,,")
        bad("s,a,,,,,,7,,")
        bad("s,a,a1,0,1,done,3,,,")
        bad("s,a,a1,x,1,done,3,,,")
        bad("s,a,a1,1,1,done,3,9,,")
        // Equal numbers and different steps are fine.
        Metrics.compute(Metrics.parse(badHead + "s,a,a1,2,1,done,3,,,\ns,b,b1,1,1,done,3,,,\n"))
    }

    @Test
    fun noBlindRatingsGiveNoAgreementOrKappa() {
        val csv = "sessionId,stepId,attemptId,attemptNumber,promptLevel,verdict,level,correctedLevel,blindVerdict,clipFile\n" +
            "s,a,a1,1,1,done,3,,,\n"
        val result = Metrics.compute(Metrics.parse(csv))
        assertNull(result.agreement)
        assertNull(result.kappa)
        assertNull(result.agreementMet)
        assertEquals(0.0, result.cannotTellRate!!, 0.0)
        assertTrue(Metrics.compute(emptyList()).cannotTellRate == null)
    }

    @Test
    fun kappaEdgeCasesAndParsing() {
        assertNull(Metrics.quadraticKappa(emptyList()))
        assertNull(Metrics.quadraticKappa(listOf(2 to 2, 2 to 2)))
        assertEquals(1.0, Metrics.quadraticKappa(listOf(1 to 1, 3 to 3))!!, 1e-12)
        assertEquals("=x", Metrics.unguard("'=x"))
        assertEquals("'a", Metrics.unguard("'a"))
        assertThrows(IllegalArgumentException::class.java) { Metrics.parseLevel("4") }
        val rows = Metrics.parse("a,b\r\n\"x,\"\"y\"\"\",'-1\r\n\nz,w")
        assertEquals(listOf("x,\"y\"", "-1", "z"), listOf(rows[0]["a"], rows[0]["b"], rows[1]["a"]))
        assertTrue(Metrics.parse("").isEmpty())
    }

    @Test
    fun correctionOnlyRowCountsAsChangedAndBadVerdictThrows() {
        val head = "sessionId,stepId,attemptId,attemptNumber,promptLevel,verdict,level,correctedLevel,blindVerdict,clipFile\n"
        val result = Metrics.compute(Metrics.parse(head + "s,a,,,,,,2,,\n"))
        assertEquals(1, result.correctedSteps)
        assertEquals(1, result.correctedChanged)
        assertEquals(0, result.steps)
        assertThrows(IllegalArgumentException::class.java) {
            Metrics.compute(Metrics.parse(head + "s,a,a1,1,1,done,3,,maybe,\n"))
        }
    }
}
