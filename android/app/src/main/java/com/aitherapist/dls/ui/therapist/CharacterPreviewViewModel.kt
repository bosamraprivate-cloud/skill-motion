import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import com.aitherapist.dls.catalog.CharacterAssets
import com.aitherapist.dls.catalog.CharacterIndex
import dagger.Binds
import dagger.Module
import dagger.hilt.InstallIn
import dagger.hilt.android.lifecycle.HiltViewModel
import dagger.hilt.android.qualifiers.ApplicationContext
import dagger.hilt.components.SingletonComponent
import javax.inject.Inject
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.update
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext

/** Reads the character clip index generated by tools/art/export_clips.py. */
fun interface CharacterIndexSource {
    suspend fun load(): CharacterIndex
}

class AssetCharacterIndexSource
@Inject
constructor(@ApplicationContext private val context: Context) : CharacterIndexSource {
    override suspend fun load(): CharacterIndex = withContext(Dispatchers.IO) {
        CharacterAssets.decode(context.assets.open(CharacterAssets.INDEX_PATH).bufferedReader().use { it.readText() })
    }
}

@Module
@InstallIn(SingletonComponent::class)
abstract class CharacterPreviewModule {
    @Binds
    abstract fun bindCharacterIndexSource(impl: AssetCharacterIndexSource): CharacterIndexSource
}

@HiltViewModel
class CharacterPreviewViewModel
@Inject
constructor(private val source: CharacterIndexSource) : ViewModel() {
    private val state = MutableStateFlow<CharacterPreviewUiState>(CharacterPreviewUiState.Loading)
    val uiState: StateFlow<CharacterPreviewUiState> = state.asStateFlow()
    private var index: CharacterIndex? = null
    private var effectOff = false

    private fun currentEffectOff() = (state.value as? CharacterPreviewUiState.Content)?.effectOff ?: effectOff

    init {
        load()
    }

    fun onEvent(event: CharacterPreviewEvent) {
        when (event) {
            CharacterPreviewEvent.Retry -> load()
            is CharacterPreviewEvent.SelectVariant -> index?.let { idx -> state.value = initial(idx, event.id) }
            is CharacterPreviewEvent.SelectReaction -> updateContent { c ->
                c.variant.reactions.firstOrNull { it.state == event.state }
                    ?.let { c.copy(selection = ClipSelection.Reaction(it), clipFailed = false) } ?: c
            }
            is CharacterPreviewEvent.SelectTask -> updateContent { c ->
                if (c.variant.tasks.none { it.id == event.id }) c else c.copy(taskId = event.id)
            }
            is CharacterPreviewEvent.SelectStep -> updateContent { c ->
                c.steps.firstOrNull { it.id == event.id }
                    ?.let { c.copy(selection = ClipSelection.Step(it), clipFailed = false) } ?: c
            }
            is CharacterPreviewEvent.SetEffectOff -> updateContent { it.copy(effectOff = event.off, clipFailed = false) }
            CharacterPreviewEvent.ClipFailed -> updateContent { it.copy(clipFailed = true) }
        }
    }

    private fun load() {
        effectOff = currentEffectOff() // keep the switch across Retry; Loading below would lose it
        state.value = CharacterPreviewUiState.Loading
        viewModelScope.launch {
            state.value =
                try {
                    val idx = source.load()
                    index = idx
                    initial(idx, idx.variants.firstOrNull()?.id)
                } catch (e: CancellationException) {
                    throw e
                } catch (
                    @Suppress("TooGenericExceptionCaught") e: Exception
                ) {
                    // Reason is the exception type only, never its message.
                    CharacterPreviewUiState.Error(e::class.simpleName ?: "unknown")
                }
        }
    }

    private fun initial(idx: CharacterIndex, variantId: String?): CharacterPreviewUiState {
        val variant = idx.variants.firstOrNull { it.id == variantId } ?: return CharacterPreviewUiState.Empty
        if (state.value is CharacterPreviewUiState.Content) effectOff = currentEffectOff()
        return CharacterPreviewUiState.Content(
            variants = idx.variants.map { it.id },
            variant = variant,
            taskId = variant.tasks.firstOrNull()?.id,
            selection = variant.reactions.firstOrNull()?.let { ClipSelection.Reaction(it) },
            effectOff = effectOff
        )
    }

    private fun updateContent(transform: (CharacterPreviewUiState.Content) -> CharacterPreviewUiState.Content) {
        state.update { if (it is CharacterPreviewUiState.Content) transform(it) else it }
    }
}
